/**
 * Regenerates lib/markets/test-vectors.json from the TypeScript implementation.
 * The Rust program tests (programs/plain-markets/.../tests/vectors.rs) and node tests
 * (tests/markets-vectors.test.ts) both assert against the committed file, so any divergence
 * between the two implementations fails CI.
 *
 *   npx tsx scripts/markets-vectors.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import bs58 from "bs58";
import { sha256 } from "@noble/hashes/sha256";

import { couponPerUnit, finalPerUnit, partialRedeemUnits, pricePerUnit } from "../lib/markets/entitlements";
import { buildSnapshotTree, canonicalSnapshotJson, nodeHash, snapshotHash, toHex, type Holding } from "../lib/markets/merkle";

const key = (label: string) => bs58.encode(sha256(new TextEncoder().encode(`plain-markets-vector:${label}`)));
const tryOrNull = (f: () => bigint) => {
  try {
    return f().toString();
  } catch {
    return null;
  }
};

const MAX = ((1n << 64n) - 1n).toString();

const coupon = [
  ["1000000000", 1250, 2],
  ["100000001", 700, 4],
  ["1", 1, 12],
  ["1000000", 333, 12],
  ["999999999999", 9999, 1],
  [MAX, 10000, 1],
  [MAX, 10000, 2],
].map(([face, rate, freq]) => ({
  face,
  rateBps: rate,
  frequency: freq,
  perUnit: tryOrNull(() => couponPerUnit(BigInt(face as string), rate as number, freq as number)),
}));

const price = [
  ["1000000000", 10000],
  ["1000000000", 2500],
  ["100000001", 10050],
  ["3", 3333],
  [MAX, 20000],
].map(([face, p]) => ({ face, priceBps: p, perUnit: tryOrNull(() => pricePerUnit(BigInt(face as string), p as number)) }));

const final = [
  ["1000000000", 10000, 1250, 2],
  ["1000000000", 10000, 0, 4],
  ["123456789", 9950, 875, 12],
].map(([face, p, r, f]) => ({
  face,
  priceBps: p,
  rateBps: r,
  frequency: f,
  perUnit: tryOrNull(() => finalPerUnit(BigInt(face as string), p as number, r as number, f as number)),
}));

const partial = [
  ["3", 5000],
  ["10", 2500],
  ["1", 9999],
  ["7777", 3333],
  [MAX, 9999],
].map(([units, b]) => ({ units, redeemBps: b, redeemUnits: tryOrNull(() => partialRedeemUnits(BigInt(units as string), b as number)) }));

function treeCase(name: string, n: number, unitsOf: (i: number) => bigint) {
  const action = key(`${name}:action`);
  const holdings: Holding[] = Array.from({ length: n }, (_, i) => ({ holder: key(`${name}:holder:${i}`), units: unitsOf(i) }));
  const tree = buildSnapshotTree(action, holdings);
  const snapshot = {
    version: 1 as const,
    instrument: key(`${name}:instrument`),
    mint: key(`${name}:mint`),
    action,
    recordTs: 1_760_000_000 + n,
    slot: 400_000_000 + n,
    holdings,
  };
  return {
    name,
    action,
    // Unsorted on purpose: implementations must sort by holder bytes.
    holdings: holdings.map((h) => ({ holder: h.holder, units: h.units.toString() })),
    sortedHolders: tree.holdings.map((h) => h.holder),
    leaves: tree.leaves.map(toHex),
    root: toHex(tree.root),
    totalUnits: tree.totalUnits.toString(),
    proofs: Object.fromEntries(tree.holdings.map((h) => [h.holder, tree.proof(h.holder).map(toHex)])),
    snapshot: { json: canonicalSnapshotJson(snapshot), sha256: toHex(snapshotHash(snapshot)) },
  };
}

const vectors = {
  description:
    "Shared vectors for Plain Markets math. Generated by scripts/markets-vectors.ts; checked by Rust (tests/vectors.rs) and node (tests/markets-vectors.test.ts).",
  leafFormat: "sha256(0x00 || action[32] || holder[32] || u64le(units))",
  nodeFormat: "sha256(0x01 || min(a,b) || max(a,b))",
  coupon,
  price,
  final,
  partial,
  nodes: [
    { a: toHex(new Uint8Array(32).fill(1)), b: toHex(new Uint8Array(32).fill(2)) },
    { a: toHex(new Uint8Array(32).fill(2)), b: toHex(new Uint8Array(32).fill(1)) },
  ].map((c) => ({ ...c, hash: toHex(nodeHash(Buffer.from(c.a, "hex"), Buffer.from(c.b, "hex"))) })),
  trees: [
    treeCase("single", 1, () => 1000n),
    treeCase("pair", 2, (i) => BigInt(i + 1) * 10n),
    treeCase("five", 5, (i) => BigInt(7 * i + 3)),
    treeCase("seven", 7, (i) => (i === 3 ? (1n << 63n) : BigInt(i + 1))),
    treeCase("sixteen", 16, (i) => BigInt(1 + ((i * 37) % 11))),
  ],
};

const out = join(__dirname, "..", "lib", "markets", "test-vectors.json");
writeFileSync(out, JSON.stringify(vectors, null, 2) + "\n");
console.log(`wrote ${out}`);
